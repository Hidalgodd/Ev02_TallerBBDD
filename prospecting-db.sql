CREATE INDEX idx_interacciones_contacto  ON interacciones(id_contacto);
CREATE INDEX idx_interacciones_proximo   ON interacciones(proximo_contacto);
CREATE INDEX idx_oportunidades_empresa   ON oportunidades(id_empresa);
CREATE INDEX idx_oportunidades_etapa     ON oportunidades(etapa);
CREATE INDEX idx_empresa_actividad_act   ON empresa_actividad(id_actividad);
CREATE INDEX idx_empresa_fuente_fuente   ON empresa_fuente(id_fuente);
