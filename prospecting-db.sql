CREATE TABLE empresas (
    id_empresa       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rut              VARCHAR2(12)  NOT NULL,
    razon_social     VARCHAR2(200) NOT NULL,
    nombre_comercial VARCHAR2(200),
    sitio_web        VARCHAR2(255),
    trabajadores     NUMBER(10),
    tramo_ventas     VARCHAR2(100),
    score            NUMBER(3) DEFAULT 0,
    prioridad        VARCHAR2(1),
    estado           VARCHAR2(30) DEFAULT 'PENDIENTE' NOT NULL,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_empresas_rut UNIQUE (rut),
    CONSTRAINT ck_empresas_trabajadores CHECK (trabajadores >= 0),
    CONSTRAINT ck_empresas_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_empresas_prioridad CHECK (prioridad IN ('A','B','C','D')),
    CONSTRAINT ck_empresas_estado CHECK (estado IN (
        'PENDIENTE','CONTACTADO','INTERESADO','REUNION',
        'COTIZACION','CLIENTE','NO_INTERESADO','NO_CONTACTAR'))
);

CREATE OR REPLACE TRIGGER trg_empresas_updated_at
BEFORE UPDATE ON empresas
FOR EACH ROW
BEGIN
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

CREATE TABLE actividades (
    id_actividad NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_sii   VARCHAR2(20)  NOT NULL,
    descripcion  VARCHAR2(300) NOT NULL,
    CONSTRAINT uq_actividades_codigo UNIQUE (codigo_sii)
);

CREATE TABLE empresa_actividad (
    id_empresa   NUMBER NOT NULL,
    id_actividad NUMBER NOT NULL,
    es_principal NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_empresa_actividad PRIMARY KEY (id_empresa, id_actividad),
    CONSTRAINT ck_ea_principal CHECK (es_principal IN (0,1)),
    CONSTRAINT fk_empresa_actividad_empresa
        FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_empresa_actividad_actividad
        FOREIGN KEY (id_actividad) REFERENCES actividades(id_actividad) ON DELETE CASCADE
);

CREATE TABLE ubicaciones (
    id_ubicacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa   NUMBER NOT NULL,
    region       VARCHAR2(100) NOT NULL,
    comuna       VARCHAR2(100) NOT NULL,
    direccion    VARCHAR2(255),
    es_principal NUMBER(1) DEFAULT 0 NOT NULL,
    CONSTRAINT ck_ubic_principal CHECK (es_principal IN (0,1)),
    CONSTRAINT fk_ubicacion_empresa
        FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE CASCADE
);

CREATE TABLE contactos (
    id_contacto  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa   NUMBER NOT NULL,
    nombre       VARCHAR2(150) NOT NULL,
    cargo        VARCHAR2(150),
    email        VARCHAR2(255),
    telefono     VARCHAR2(30),
    linkedin_url VARCHAR2(500),
    es_principal NUMBER(1) DEFAULT 0 NOT NULL,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_cont_principal CHECK (es_principal IN (0,1)),
    CONSTRAINT fk_contacto_empresa
        FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE CASCADE
);

CREATE TABLE interacciones (
    id_interaccion   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa       NUMBER NOT NULL,
    id_contacto      NUMBER,
    fecha            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    tipo             VARCHAR2(30) NOT NULL,
    resultado        VARCHAR2(100),
    observaciones    CLOB,
    proximo_contacto TIMESTAMP,
    CONSTRAINT ck_inter_tipo CHECK (tipo IN ('LLAMADA','EMAIL','WHATSAPP','REUNION','OTRO')),
    CONSTRAINT fk_interaccion_empresa
        FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_interaccion_contacto
        FOREIGN KEY (id_contacto) REFERENCES contactos(id_contacto) ON DELETE SET NULL
);

CREATE TABLE oportunidades (
    id_oportunidad        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa            NUMBER NOT NULL,
    producto              VARCHAR2(200),
    etapa                 VARCHAR2(30) DEFAULT 'PROSPECTO' NOT NULL,
    valor_estimado        NUMBER(12,2),
    probabilidad          NUMBER(3) DEFAULT 0,
    fecha_cierre_estimada DATE,
    created_at            TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_opor_etapa CHECK (etapa IN (
        'PROSPECTO','CONTACTO','CALIFICADO','REUNION',
        'PROPUESTA','NEGOCIACION','GANADA','PERDIDA')),
    CONSTRAINT ck_opor_valor CHECK (valor_estimado >= 0),
    CONSTRAINT ck_opor_prob CHECK (probabilidad BETWEEN 0 AND 100),
    CONSTRAINT fk_oportunidad_empresa
        FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE CASCADE
);

CREATE TABLE fuentes_datos (
    id_fuente       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(150) NOT NULL,
    url             VARCHAR2(500),
    descripcion     CLOB,
    fecha_obtencion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE empresa_fuente (
    id_empresa  NUMBER NOT NULL,
    id_fuente   NUMBER NOT NULL,
    fecha_carga TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_empresa_fuente PRIMARY KEY (id_empresa, id_fuente),
    CONSTRAINT fk_empresa_fuente_empresa
        FOREIGN KEY (id_empresa) REFERENCES empresas(id_empresa) ON DELETE CASCADE,
    CONSTRAINT fk_empresa_fuente_fuente
        FOREIGN KEY (id_fuente) REFERENCES fuentes_datos(id_fuente) ON DELETE CASCADE
);

CREATE TABLE auditoria_estado_empresa (
    id_auditoria    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa      NUMBER NOT NULL,
    estado_anterior VARCHAR2(30),
    estado_nuevo    VARCHAR2(30),
    usuario         VARCHAR2(100),
    fecha           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);


